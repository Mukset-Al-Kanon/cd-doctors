// Helper function to get Upazilas for any district (with NFC normalization support)
export function getUpazilasForDistrict(districtName: string): string[] {
  if (!districtName) return [];
  const clean = districtName.replace(' জেলা', '').trim();
  const nfc = clean.normalize('NFC');

  if (BANGLADESH_LOCATIONS[clean]) return BANGLADESH_LOCATIONS[clean];
  if (BANGLADESH_LOCATIONS[nfc]) return BANGLADESH_LOCATIONS[nfc];

  for (const [key, val] of Object.entries(BANGLADESH_LOCATIONS)) {
    if (key.normalize('NFC') === nfc) {
      return val;
    }
  }
  return [];
}
